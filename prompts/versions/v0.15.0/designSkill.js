export const DESIGN_SKILL = `
## 设计素养（内置 skill，必须遵守）

### 1. 先定阅读顺序，再谈装饰
读者第一眼：报头 → 主标题 → 主图 → 副标题 → 正文。层级只能有一个主角；
任何与这条视线竞争的装饰都必须删掉。

### 2. 网格与留白
- 所有元素对齐同一套边距（版心左右 ≥ 4%），细线只用于分区，不用于装饰。
- 留白是版面的一部分：段落之间用 1 个行高的呼吸，不用卡片、圆角、阴影。
- 不堆叠：同一区块最多 3 个视觉元素。

### 3. 字体系统
- 只允许 3 组字号层级：展示级（标题）、阅读级（正文）、标注级（日期/图注/页脚）。
- 中文正文行高 1.75–2.0，每行 18–26 个汉字；标题字距收紧，英文小标字距放宽。
- 衬线标题 + 无衬线正文（serif_sans）最稳妥；全衬线（serif_serif）适合纪念；
  单一超级家族（superfamily）适合极简。不得混用第四种字体。

### 4. 色彩纪律
- 一套版式只有一个强调色；强调色只出现在标题、线条、标签、横幅上。
- 60-30-10：纸底 60%、墨色 30%、强调色 ≤10%。
- 正文永远用墨色（text），对比度 ≥ 4.5:1；不用浅灰写长文。

### 5. 图片
- 一张主图胜过三张小图。主图必须被裁切为明确的画幅比例，不做自由缩放。
- 黑白半调 / 双色调是对齐版面色温的手段，不是滤镜堆叠。
- 图注写"看见了什么"，不重复标题。

### 6. 印刷感
- 报头用上下双细线，日期栏用单细线；线宽不超过 1.5px（96dpi 下）。
- 强调色横幅可以满版出血，但文字必须与边缘保持 ≥ 3% 安全距。
- 页脚放免责声明、期号、页码，给版面一个"结束"。

### 7. 反 AI 味清单（违反即不合格）
- 禁止紫粉蓝渐变、玻璃拟态、霓虹色、圆角卡片、emoji 图标。
- 禁止假数据、假引语、假品牌、假链接、Lorem ipsum。
- 禁止把大段中文塞进图片里；文字必须由模板引擎渲染。
- 禁止三套方案共用同一版式或同一配色。

### 8. 文案纪律
- 报纸腔 ≠ 标题党：克制、第三人称、具体名词、不喊口号。
- 标题 ≤15 字，副标题 ≤25 字，导语 150–220 字、2–4 段。
- 只"报道"日常小事，不编造真实新闻事件、人物言论或数据。
`.trim()

